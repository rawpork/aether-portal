// Scans .aether/skills/AEPS/ for SKILL.md playbooks (folders may be symlinks or junctions to the real skill repos) and
// writes src/generated/aeps-skills.js, which the Worker serves to signed-in users at GET /api/skills/aeps. The playbooks
// are proprietary, so they are bundled into the Worker behind the session check, never into the public assets folder.
// Runs as part of `npm run build:client` (and so before every `wrangler deploy` / `wrangler dev`).
import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS_DIR = join(ROOT, '.aether', 'skills', 'AEPS');
const OUT_FILE = join(ROOT, 'src', 'generated', 'aeps-skills.js');
const MAX_BODY_CHARS = 20000;
const MAX_DEPTH = 6;

// Minimal YAML front matter reader: top-level "key: value" pairs only, which is all SKILL.md headers use.
export function parseSkill(text) {
	const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
	const meta = {};
	if (match) {
		for (const line of match[1].split(/\r?\n/)) {
			const kv = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
			if (kv) meta[kv[1]] = kv[2].replace(/^["']|["']$/g, '').trim();
		}
	}
	const body = match ? text.slice(match[0].length) : text;
	const heading = /^#\s+(.+)$/m.exec(body);
	return { meta, body, heading: heading ? heading[1].trim() : '' };
}

async function findSkillFiles(dir, depth = 0, seen = new Set()) {
	if (depth > MAX_DEPTH) return [];
	let entries;
	try {
		entries = await readdir(dir, { withFileTypes: true });
	} catch {
		return [];
	}
	const found = [];
	for (const entry of entries) {
		if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
		const full = join(dir, entry.name);
		// stat() follows symlinks and junctions, so linked skill folders are scanned like local ones.
		const info = await stat(full).catch(() => null);
		if (!info) continue;
		if (info.isDirectory()) {
			const key = info.dev + ':' + info.ino;
			if (seen.has(key)) continue;
			seen.add(key);
			found.push(...(await findSkillFiles(full, depth + 1, seen)));
		} else if (entry.name === 'SKILL.md') {
			found.push(full);
		}
	}
	return found;
}

export async function buildSkillsIndex(skillsDir = SKILLS_DIR) {
	const files = (await findSkillFiles(skillsDir)).sort();
	const skills = [];
	for (const file of files) {
		const text = await readFile(file, 'utf8');
		const { meta, body, heading } = parseSkill(text);
		const rel = relative(skillsDir, dirname(file)).split(sep).join('/');
		const info = await stat(file);
		skills.push({
			id: rel || 'root',
			name: meta.name || heading || rel.split('/').pop() || 'Unnamed skill',
			description: meta.description || '',
			version: meta.version || '',
			path: '.aether/skills/AEPS/' + (rel ? rel + '/' : '') + 'SKILL.md',
			updated_at: info.mtime.toISOString(),
			body: body.length > MAX_BODY_CHARS ? body.slice(0, MAX_BODY_CHARS) + '\n…' : body,
		});
	}
	return skills;
}

const skills = await buildSkillsIndex();
await mkdir(dirname(OUT_FILE), { recursive: true });
await writeFile(
	OUT_FILE,
	'// Generated by scripts/build-skills-index.mjs from .aether/skills/AEPS/. Do not edit.\n' +
		'export const AEPS_SKILLS = ' +
		JSON.stringify({ generated_at: new Date().toISOString(), skills }, null, '\t') +
		';\n',
);
console.log('AEPS skills index: ' + skills.length + ' playbook' + (skills.length === 1 ? '' : 's') + ' -> ' + relative(ROOT, OUT_FILE));
